export const NO_CARD_IDS = new Set([
  "the_tower",
  "the_moon",
  "the_hanged_man",
  "the_devil",
  "death",
  "five_of_cups",
  "five_of_pentacles",
  "five_of_swords",
  "five_of_wands",
  "seven_of_swords",
  "eight_of_swords",
  "nine_of_swords",
  "ten_of_swords",
  "three_of_swords",
]);

export function getYesNoVerdict(cardId, isReversed) {
  const baseYes = YES_CARD_IDS.has(cardId);
  const baseNo = NO_CARD_IDS.has(cardId);
  if (!isReversed) {
    if (baseYes)
      return {
        verdict: "YES",
        color: "#34D399",
        bg: "rgba(52,211,153,0.1)",
        msg: "The cards align in your favor. The energy points forward — trust yourself and move ahead.",
      };
    if (baseNo)
      return {
        verdict: "NO",
        color: "#F87171",
        bg: "rgba(248,113,113,0.1)",
        msg: "The cards counsel pause or caution. Reflect on what may need to shift before proceeding.",
      };
  }
  return {
    verdict: "MAYBE",
    color: "#FBBF24",
    bg: "rgba(251,191,36,0.1)",
    msg: "The answer is uncertain or in flux. Gather more clarity before deciding.",
  };
}

// ── Moon-phase card weighting ─────────────────────────────────────────────────
export function getMoonPhaseWeights(phaseName) {
  const p = (phaseName || "").toLowerCase();
  if (p.includes("new moon"))
    return (c) => (c.arcana === "major" || c.id.includes("ace") ? 4 : 1);
  if (p.includes("waxing crescent")) return (c) => (c.suit === "wands" ? 3 : 1);
  if (p.includes("first quarter"))
    return (c) => (c.suit === "wands" || c.suit === "pentacles" ? 2 : 1);
  if (p.includes("waxing gibbous"))
    return (c) => (c.arcana === "major" ? 2 : 1);
  if (p.includes("full moon")) return (c) => (c.suit === "cups" ? 4 : 1);
  if (p.includes("waning gibbous")) return (c) => (c.suit === "cups" ? 2 : 1);
  if (p.includes("last quarter") || p.includes("third quarter"))
    return (c) => (c.suit === "swords" ? 3 : 1);
  if (p.includes("waning crescent"))
    return (c) =>
      [
        "the_hermit",
        "the_moon",
        "the_hanged_man",
        "the_high_priestess",
      ].includes(c.id) || c.suit === "swords"
        ? 4
        : 1;
  return () => 1;
}
